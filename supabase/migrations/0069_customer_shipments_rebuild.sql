create or replace function public.customer_shipment_open_qty(
  p_order_id uuid,
  p_product_id uuid,
  p_size_id uuid,
  p_drop_id uuid
)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(c.qty), 0)::integer
  from public.customer_shipment_products sp
  join public.customer_shipments s on s.id = sp.customer_shipment_id
  join public.customer_shipment_cells c on c.customer_shipment_product_id = sp.id
  where sp.customer_order_id = p_order_id
    and sp.product_id = p_product_id
    and c.size_id = p_size_id
    and c.drop_id = p_drop_id
    and s.status not in ('shipped', 'canceled');
$$;

create or replace function public.customer_shipment_address_key(
  p_line1 text,
  p_line2 text,
  p_city text,
  p_region text,
  p_postal_code text,
  p_country text
)
returns text
language sql
immutable
as $$
  select lower(concat_ws(
    '|',
    btrim(coalesce(p_line1, '')),
    btrim(coalesce(p_line2, '')),
    btrim(coalesce(p_city, '')),
    btrim(coalesce(p_region, '')),
    btrim(coalesce(p_postal_code, '')),
    btrim(coalesce(p_country, ''))
  ));
$$;

create or replace function public.customer_shipments_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  has_lines boolean;
  has_orders boolean;
begin
  if tg_op = 'DELETE' then
    if old.status = 'shipped' then
      raise exception 'A shipped shipment cannot be deleted';
    end if;
    return old;
  end if;

  if tg_op = 'INSERT' then
    if new.status <> 'pending' then
      raise exception 'A shipment starts as pending';
    end if;
    new.date_shipped := null;
    new.created_by := auth.uid();
  else
    new.shipment_no := old.shipment_no;
    new.created_at := old.created_at;
    new.created_by := old.created_by;

    if old.status = 'canceled' then
      raise exception 'A canceled shipment cannot be changed';
    end if;

    if old.status = 'shipped' then
      if (to_jsonb(new) - 'tracking_no' - 'notes' - 'updated_at' - 'updated_by')
         is distinct from
         (to_jsonb(old) - 'tracking_no' - 'notes' - 'updated_at' - 'updated_by') then
        raise exception 'A shipped shipment cannot be changed';
      end if;
    else
      if new.status = 'shipped' then
        if coalesce(current_setting('app.customer_shipping', true), '') <> '1' then
          raise exception 'Use Ship to ship a shipment';
        end if;
        if new.date_shipped is null then
          new.date_shipped := current_date;
        end if;
      else
        new.date_shipped := null;
      end if;

      select
        exists (
          select 1
          from public.customer_shipment_products sp
          where sp.customer_shipment_id = old.id
        ),
        exists (
          select 1
          from public.customer_shipment_products sp
          where sp.customer_shipment_id = old.id
            and sp.customer_order_id is not null
        )
      into has_lines, has_orders;

      if has_lines and new.customer_id is distinct from old.customer_id then
        raise exception 'Remove the products before changing the customer';
      end if;

      if has_orders and row(
        new.terms, new.shipment_method_id, new.shipping_method, new.sales_rep_id,
        new.ship_address_line1, new.ship_address_line2, new.ship_city,
        new.ship_region, new.ship_postal_code, new.ship_country,
        new.bill_address_line1, new.bill_address_line2, new.bill_city,
        new.bill_region, new.bill_postal_code, new.bill_country
      ) is distinct from row(
        old.terms, old.shipment_method_id, old.shipping_method, old.sales_rep_id,
        old.ship_address_line1, old.ship_address_line2, old.ship_city,
        old.ship_region, old.ship_postal_code, old.ship_country,
        old.bill_address_line1, old.bill_address_line2, old.bill_city,
        old.bill_region, old.bill_postal_code, old.bill_country
      ) then
        raise exception 'Remove the orders before changing the addresses, terms, shipping method, or sales rep';
      end if;
    end if;
  end if;

  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end;
$$;

drop trigger if exists customer_shipments_guard on public.customer_shipments;
create trigger customer_shipments_guard
  before insert or update or delete on public.customer_shipments
  for each row
  execute function public.customer_shipments_guard();

create or replace function public.add_order_to_customer_shipment(
  p_shipment_id uuid,
  p_order_id uuid
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  shp public.customer_shipments;
  ord public.customer_orders;
  rec record;
  has_orders boolean;
  new_line uuid;
  added integer := 0;
begin
  if not (public.is_admin() or public.is_warehouse()) then
    raise exception 'not allowed';
  end if;

  select * into shp
  from public.customer_shipments
  where id = p_shipment_id
  for update;
  if not found then
    raise exception 'shipment not found';
  end if;
  if shp.status in ('shipped', 'canceled') then
    raise exception 'This shipment can no longer be changed';
  end if;

  select * into ord from public.customer_orders where id = p_order_id;
  if not found then
    raise exception 'order not found';
  end if;
  if ord.customer_id <> shp.customer_id then
    raise exception 'That order belongs to another customer';
  end if;
  if ord.status not in ('approved', 'picking', 'back_order') then
    raise exception 'Only an approved order can be shipped';
  end if;

  select exists (
    select 1
    from public.customer_shipment_products sp
    where sp.customer_shipment_id = shp.id
      and sp.customer_order_id is not null
  )
  into has_orders;

  if has_orders then
    if public.customer_shipment_address_key(
         ord.ship_address_line1, ord.ship_address_line2, ord.ship_city,
         ord.ship_region, ord.ship_postal_code, ord.ship_country
       ) <> public.customer_shipment_address_key(
         shp.ship_address_line1, shp.ship_address_line2, shp.ship_city,
         shp.ship_region, shp.ship_postal_code, shp.ship_country
       ) then
      raise exception 'Order % has a different ship-to address', ord.order_no;
    end if;
    if public.customer_shipment_address_key(
         ord.bill_address_line1, ord.bill_address_line2, ord.bill_city,
         ord.bill_region, ord.bill_postal_code, ord.bill_country
       ) <> public.customer_shipment_address_key(
         shp.bill_address_line1, shp.bill_address_line2, shp.bill_city,
         shp.bill_region, shp.bill_postal_code, shp.bill_country
       ) then
      raise exception 'Order % has a different bill-to address', ord.order_no;
    end if;
    if lower(btrim(coalesce(ord.terms, ''))) <> lower(btrim(coalesce(shp.terms, ''))) then
      raise exception 'Order % has different terms', ord.order_no;
    end if;
    if ord.shipment_method_id is distinct from shp.shipment_method_id
       or lower(btrim(coalesce(ord.shipping_method, '')))
          <> lower(btrim(coalesce(shp.shipping_method, ''))) then
      raise exception 'Order % has a different shipping method', ord.order_no;
    end if;
    if ord.sales_rep_id is distinct from shp.sales_rep_id then
      raise exception 'Order % has a different sales rep', ord.order_no;
    end if;
  else
    update public.customer_shipments
    set
      terms = ord.terms,
      shipment_method_id = ord.shipment_method_id,
      shipping_method = ord.shipping_method,
      sales_rep_id = ord.sales_rep_id,
      ship_address_line1 = ord.ship_address_line1,
      ship_address_line2 = ord.ship_address_line2,
      ship_city = ord.ship_city,
      ship_region = ord.ship_region,
      ship_postal_code = ord.ship_postal_code,
      ship_country = ord.ship_country,
      bill_address_line1 = ord.bill_address_line1,
      bill_address_line2 = ord.bill_address_line2,
      bill_city = ord.bill_city,
      bill_region = ord.bill_region,
      bill_postal_code = ord.bill_postal_code,
      bill_country = ord.bill_country
    where id = shp.id;
  end if;

  for rec in
    select cop.product_id, cop.price, cop.qty, p.type
    from public.customer_order_products cop
    join public.products p on p.id = cop.product_id
    where cop.customer_order_id = ord.id
      and cop.status in ('pending', 'back_order')
      and not exists (
        select 1
        from public.customer_shipment_products sp
        where sp.customer_shipment_id = shp.id
          and sp.customer_order_id = ord.id
          and sp.product_id = cop.product_id
      )
  loop
    if rec.type = 1 then
      if not exists (
        select 1
        from public.customer_order_cells c
        where c.customer_order_id = ord.id
          and c.product_id = rec.product_id
          and c.qty - c.qty_shipped
              - public.customer_shipment_open_qty(ord.id, rec.product_id, c.size_id, c.drop_id) > 0
      ) then
        continue;
      end if;

      insert into public.customer_shipment_products (
        customer_shipment_id, customer_order_id, product_id
      )
      values (shp.id, ord.id, rec.product_id)
      returning id into new_line;

      insert into public.customer_shipment_cells (
        customer_shipment_product_id, size_id, drop_id, qty, price
      )
      select
        new_line,
        c.size_id,
        c.drop_id,
        greatest(
          0,
          c.qty - c.qty_shipped
            - public.customer_shipment_open_qty(ord.id, rec.product_id, c.size_id, c.drop_id)
        ),
        rec.price + coalesce(c.price, 0)
      from public.customer_order_cells c
      where c.customer_order_id = ord.id
        and c.product_id = rec.product_id
        and c.qty > 0;
    else
      if exists (
        select 1
        from public.customer_shipment_products sp
        join public.customer_shipments s on s.id = sp.customer_shipment_id
        where sp.customer_order_id = ord.id
          and sp.product_id = rec.product_id
          and s.status <> 'canceled'
      ) then
        continue;
      end if;

      insert into public.customer_shipment_products (
        customer_shipment_id, customer_order_id, product_id, qty, price
      )
      values (
        shp.id,
        ord.id,
        rec.product_id,
        case when rec.type = 3 then 1 else coalesce(rec.qty, 1) end,
        rec.price
      );
    end if;
    added := added + 1;
  end loop;

  if added = 0 then
    raise exception 'Nothing is left to ship on order %', ord.order_no;
  end if;
  return added;
end;
$$;

create or replace function public.ship_customer_shipment(
  p_shipment_id uuid,
  p_date_shipped date default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  shp public.customer_shipments;
  rec record;
  on_hand integer;
begin
  if not (public.is_admin() or public.is_warehouse()) then
    raise exception 'not allowed';
  end if;

  select * into shp
  from public.customer_shipments
  where id = p_shipment_id
  for update;
  if not found then
    raise exception 'shipment not found';
  end if;
  if shp.status in ('shipped', 'canceled') then
    raise exception 'This shipment can no longer be changed';
  end if;
  if not exists (
    select 1
    from public.customer_shipment_products sp
    where sp.customer_shipment_id = shp.id
  ) then
    raise exception 'Add an order before shipping';
  end if;

  for rec in
    select distinct o.order_no, o.status
    from public.customer_shipment_products sp
    join public.customer_orders o on o.id = sp.customer_order_id
    where sp.customer_shipment_id = shp.id
  loop
    if rec.status not in ('approved', 'picking', 'back_order') then
      raise exception 'Order % can no longer be shipped', rec.order_no;
    end if;
  end loop;

  for rec in
    select
      c.qty,
      o.order_no,
      cop.status as line_status,
      oc.qty as ordered,
      oc.qty_shipped as shipped,
      coalesce(nullif(btrim(p.name), ''), 'Product') as product_name,
      sz.code as size_code
    from public.customer_shipment_products sp
    join public.customer_shipment_cells c on c.customer_shipment_product_id = sp.id
    join public.customer_orders o on o.id = sp.customer_order_id
    join public.customer_order_products cop
      on cop.customer_order_id = sp.customer_order_id
     and cop.product_id = sp.product_id
    join public.products p on p.id = sp.product_id
    join public.size_chart_sizes sz on sz.id = c.size_id
    left join public.customer_order_cells oc
      on oc.customer_order_id = sp.customer_order_id
     and oc.product_id = sp.product_id
     and oc.size_id = c.size_id
     and oc.drop_id = c.drop_id
    where sp.customer_shipment_id = shp.id
      and c.qty > 0
  loop
    if rec.line_status not in ('pending', 'back_order') then
      raise exception '% on order % is no longer open', rec.product_name, rec.order_no;
    end if;
    if rec.ordered is null or rec.qty > rec.ordered - rec.shipped then
      raise exception '% size % on order %: only % left to ship',
        rec.product_name,
        rec.size_code,
        rec.order_no,
        greatest(0, coalesce(rec.ordered - rec.shipped, 0));
    end if;
  end loop;

  for rec in
    select
      sp.product_id,
      c.size_id,
      c.drop_id,
      sum(c.qty)::integer as qty,
      coalesce(nullif(btrim(max(p.name)), ''), 'Product') as product_name,
      max(sz.code) as size_code
    from public.customer_shipment_products sp
    join public.customer_shipment_cells c on c.customer_shipment_product_id = sp.id
    join public.products p on p.id = sp.product_id
    join public.size_chart_sizes sz on sz.id = c.size_id
    where sp.customer_shipment_id = shp.id
      and c.qty > 0
    group by sp.product_id, c.size_id, c.drop_id
  loop
    on_hand := null;
    select i.qty_on_hand into on_hand
    from public.inventory i
    where i.product_id = rec.product_id
      and i.size_id = rec.size_id
      and i.drop_id = rec.drop_id
    for update;

    if coalesce(on_hand, 0) < rec.qty then
      raise exception 'Not enough on hand for % size %: % on hand, % to ship',
        rec.product_name,
        rec.size_code,
        coalesce(on_hand, 0),
        rec.qty;
    end if;

    update public.inventory i
    set qty_on_hand = i.qty_on_hand - rec.qty
    where i.product_id = rec.product_id
      and i.size_id = rec.size_id
      and i.drop_id = rec.drop_id;

    insert into public.stock_movements (
      type, qty, product_id, size_id, drop_id, customer_id, customer_shipment_id, user_id
    )
    values (
      'ship', rec.qty, rec.product_id, rec.size_id, rec.drop_id, shp.customer_id, shp.id, auth.uid()
    );
  end loop;

  update public.customer_order_cells oc
  set qty_shipped = oc.qty_shipped + c.qty
  from public.customer_shipment_products sp
  join public.customer_shipment_cells c on c.customer_shipment_product_id = sp.id
  where sp.customer_shipment_id = shp.id
    and c.qty > 0
    and oc.customer_order_id = sp.customer_order_id
    and oc.product_id = sp.product_id
    and oc.size_id = c.size_id
    and oc.drop_id = c.drop_id;

  update public.customer_order_products cop
  set status = 'complete'
  from public.customer_shipment_products sp
  join public.products p on p.id = sp.product_id
  where sp.customer_shipment_id = shp.id
    and cop.customer_order_id = sp.customer_order_id
    and cop.product_id = sp.product_id
    and cop.status in ('pending', 'back_order')
    and (
      p.type <> 1
      or (
        exists (
          select 1
          from public.customer_order_cells oc
          where oc.customer_order_id = cop.customer_order_id
            and oc.product_id = cop.product_id
            and oc.qty > 0
        )
        and not exists (
          select 1
          from public.customer_order_cells oc
          where oc.customer_order_id = cop.customer_order_id
            and oc.product_id = cop.product_id
            and oc.qty_shipped < oc.qty
        )
      )
    );

  perform set_config('app.customer_shipping', '1', true);
  update public.customer_shipments
  set status = 'shipped', date_shipped = coalesce(p_date_shipped, current_date)
  where id = shp.id;
  perform set_config('app.customer_shipping', '', true);
end;
$$;

create or replace function public.retarget_drop(p_from uuid, p_to uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_from is null or p_to is null or p_from = p_to then
    return;
  end if;

  insert into public.product_drops (product_id, drop_id)
  select product_id, p_to from public.product_drops where drop_id = p_from
  on conflict do nothing;
  delete from public.product_drops where drop_id = p_from;

  insert into public.inventory (product_id, size_id, drop_id, qty_on_hand, reorder_point)
  select product_id, size_id, p_to, qty_on_hand, reorder_point
  from public.inventory
  where drop_id = p_from
  on conflict (product_id, size_id, drop_id) do update
  set
    qty_on_hand = public.inventory.qty_on_hand + excluded.qty_on_hand,
    reorder_point = greatest(public.inventory.reorder_point, excluded.reorder_point);
  delete from public.inventory where drop_id = p_from;

  insert into public.product_price_upcharges (product_id, size_id, drop_id, upcharge_amount)
  select product_id, size_id, p_to, upcharge_amount
  from public.product_price_upcharges
  where drop_id = p_from
  on conflict (product_id, size_id, drop_id) do update
  set upcharge_amount = greatest(
    public.product_price_upcharges.upcharge_amount,
    excluded.upcharge_amount
  );
  delete from public.product_price_upcharges where drop_id = p_from;

  insert into public.customer_shipment_cells (
    customer_shipment_product_id, size_id, drop_id, qty, price
  )
  select customer_shipment_product_id, size_id, p_to, qty, price
  from public.customer_shipment_cells
  where drop_id = p_from
  on conflict (customer_shipment_product_id, size_id, drop_id) do update
  set qty = public.customer_shipment_cells.qty + excluded.qty;
  delete from public.customer_shipment_cells where drop_id = p_from;

  insert into public.cutting_shipment_cells (
    cutting_shipment_product_id, size_id, drop_id, qty
  )
  select cutting_shipment_product_id, size_id, p_to, qty
  from public.cutting_shipment_cells
  where drop_id = p_from
  on conflict (cutting_shipment_product_id, size_id, drop_id) do update
  set qty = public.cutting_shipment_cells.qty + excluded.qty;
  delete from public.cutting_shipment_cells where drop_id = p_from;

  insert into public.vendor_shipment_cells (
    shipment_product_id, size_id, drop_id, qty
  )
  select shipment_product_id, size_id, p_to, qty
  from public.vendor_shipment_cells
  where drop_id = p_from
  on conflict (shipment_product_id, size_id, drop_id) do update
  set qty = public.vendor_shipment_cells.qty + excluded.qty;
  delete from public.vendor_shipment_cells where drop_id = p_from;

  update public.stock_movements set drop_id = p_to where drop_id = p_from;
end;
$$;

