  on public.customer_shipment_products (customer_shipment_id, product_id)
  where customer_order_id is null;

create index if not exists customer_shipment_products_order_idx
  on public.customer_shipment_products (customer_order_id, product_id);

create table if not exists public.customer_shipment_cells (
  customer_shipment_product_id uuid not null
