create policy cust_ship_staff on public.customer_shipments
  for all to authenticated
  using (public.is_admin() or public.is_warehouse())
  with check (public.is_admin() or public.is_warehouse());

drop policy if exists cust_ship_rep_read on public.customer_shipments;
create policy cust_ship_rep_read on public.customer_shipments
  for select to authenticated
  using (
    public.current_role() = 'sales_rep'
    and exists (
      select 1
      from public.customers c
      where c.id = customer_shipments.customer_id
        and c.sales_rep_id = auth.uid()
    )
  );

drop policy if exists cshp_read on public.customer_shipment_products;
create policy cshp_read on public.customer_shipment_products
  for select to authenticated
  using (
    exists (
      select 1
      from public.customer_shipments s
      where s.id = customer_shipment_products.customer_shipment_id
    )
  );

drop policy if exists cshp_insert on public.customer_shipment_products;
create policy cshp_insert on public.customer_shipment_products
  for insert to authenticated
  with check (
    (public.is_admin() or public.is_warehouse())
    and public.customer_shipment_is_open(customer_shipment_id)
    and customer_order_id is null
    and exists (
      select 1
      from public.products p
      where p.id = customer_shipment_products.product_id
        and p.type in (2, 3)
    )
  );

drop policy if exists cshp_update on public.customer_shipment_products;
create policy cshp_update on public.customer_shipment_products
  for update to authenticated
  using (
    (public.is_admin() or public.is_warehouse())
    and public.customer_shipment_is_open(customer_shipment_id)
  )
  with check (
    (public.is_admin() or public.is_warehouse())
    and public.customer_shipment_is_open(customer_shipment_id)
  );

drop policy if exists cshp_delete on public.customer_shipment_products;
create policy cshp_delete on public.customer_shipment_products
  for delete to authenticated
  using (
    (public.is_admin() or public.is_warehouse())
    and public.customer_shipment_is_open(customer_shipment_id)
  );

drop policy if exists cshc_read on public.customer_shipment_cells;
create policy cshc_read on public.customer_shipment_cells
  for select to authenticated
  using (
    exists (
      select 1
      from public.customer_shipment_products sp
      where sp.id = customer_shipment_cells.customer_shipment_product_id
    )
  );

drop policy if exists cshc_update on public.customer_shipment_cells;
create policy cshc_update on public.customer_shipment_cells
  for update to authenticated
  using (
    (public.is_admin() or public.is_warehouse())
    and exists (
      select 1
      from public.customer_shipment_products sp
      where sp.id = customer_shipment_cells.customer_shipment_product_id
        and public.customer_shipment_is_open(sp.customer_shipment_id)
    )
  )
  with check (
    (public.is_admin() or public.is_warehouse())
    and exists (
      select 1
      from public.customer_shipment_products sp
      where sp.id = customer_shipment_cells.customer_shipment_product_id
        and public.customer_shipment_is_open(sp.customer_shipment_id)
    )
  );

grant select, insert, update, delete on public.customer_shipments to authenticated;
grant select, insert, update, delete on public.customer_shipment_products to authenticated;
grant select, insert, update, delete on public.customer_shipment_cells to authenticated;
grant usage, select on sequence public.customer_shipments_shipment_no_seq to authenticated;

revoke all on function public.customer_shipment_is_open(uuid) from public;
revoke all on function public.customer_shipment_open_qty(uuid, uuid, uuid, uuid) from public;
revoke all on function public.add_order_to_customer_shipment(uuid, uuid) from public;
revoke all on function public.ship_customer_shipment(uuid, date) from public;
grant execute on function public.customer_shipment_is_open(uuid) to authenticated;
grant execute on function public.customer_shipment_open_qty(uuid, uuid, uuid, uuid) to authenticated;
grant execute on function public.add_order_to_customer_shipment(uuid, uuid) to authenticated;
grant execute on function public.ship_customer_shipment(uuid, date) to authenticated;
grant execute on function public.retarget_drop(uuid, uuid) to authenticated;

notify pgrst, 'reload schema';
