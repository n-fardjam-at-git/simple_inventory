create table if not exists public.customer_shipments (
  id uuid primary key default gen_random_uuid(),
  shipment_no integer generated by default as identity,
  customer_id uuid not null references public.customers(id),
  status text not null default 'pending' check (status in (
    'pending', 'picking', 'picked', 'boxed_ready', 'shipped', 'canceled'
  )),
  terms text,
  shipment_method_id uuid references public.shipment_methods(id),
  shipping_method text,
  ship_address_line1 text,
  ship_address_line2 text,
  ship_city text,
  ship_region text,
  ship_postal_code text,
  ship_country text,
  bill_address_line1 text,
  bill_address_line2 text,
  bill_city text,
  bill_region text,
  bill_postal_code text,
  bill_country text,
  sales_rep_id uuid references public.profiles(id),
  picker_id uuid references public.profiles(id),
  tracking_no text,
  notes text,
  date_shipped date,
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (shipment_no)
);

