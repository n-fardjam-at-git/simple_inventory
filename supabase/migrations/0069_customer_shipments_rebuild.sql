  id uuid primary key default gen_random_uuid(),
  customer_shipment_id uuid not null references public.customer_shipments(id) on delete cascade,
  customer_order_id uuid references public.customer_orders(id),
  product_id uuid not null references public.products(id),
  qty integer check (qty is null or qty >= 0),
  price numeric(12,2) check (price is null or price >= 0),
  foreign key (customer_order_id, product_id)
    references public.customer_order_products (customer_order_id, product_id)
);

