create or replace function public.current_customer_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select p.customer_id from public.profiles p where p.id = auth.uid() and p.role = 'customer'),
    (select c.id from public.customers c where c.user_id = auth.uid() limit 1)
  );
$$;

create table public.customer_order_requests (
  id uuid primary key default gen_random_uuid(),
  request_no integer generated by default as identity,
  customer_id uuid not null references public.customers(id),
  status text not null default 'draft' check (status in ('draft', 'submitted', 'accepted')),
  future_season text,
  start_date date,
  cancel_date date,
  terms text,
  shipment_method_id uuid references public.shipment_methods(id),
  shipping_method text,
  transmission_method_id uuid references public.transmission_methods(id),
  transmission_method text,
  ship_address_line1 text,
  ship_address_line2 text,
  ship_city text,
  ship_region text,
  ship_postal_code text,
  ship_country text,
  bill_address_line1 text,
  bill_address_line2 text,
  bill_city text,
  bill_region text,
  bill_postal_code text,
  bill_country text,
  sales_rep_id uuid references public.profiles(id),
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  submitted_at timestamptz,
  accepted_order_id uuid references public.customer_orders(id),
  notes text,
  unique (request_no)
);

create index customer_order_requests_customer_idx
  on public.customer_order_requests (customer_id, status);

create table public.customer_order_request_products (
  request_id uuid not null references public.customer_order_requests(id) on delete cascade,
  product_id uuid not null references public.products(id),
  price numeric(12,2) not null default 0 check (price >= 0),
  qty int check (qty is null or qty >= 0),
  commission_rate numeric(5,4) check (
    commission_rate is null or (commission_rate >= 0 and commission_rate <= 1)
  ),
  primary key (request_id, product_id)
);

create table public.customer_order_request_cells (
  request_id uuid not null,
  product_id uuid not null,
  size_id uuid not null references public.size_chart_sizes(id),
  drop_id uuid not null references public.size_chart_drops(id),
  qty int not null default 0 check (qty >= 0),
  price numeric(12,2),
  primary key (request_id, product_id, size_id, drop_id),
  foreign key (request_id, product_id)
    references public.customer_order_request_products (request_id, product_id)
    on delete cascade
);

create or replace function public.request_visible(p_request_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.customer_order_requests r
    join public.customers c on c.id = r.customer_id
    where r.id = p_request_id
      and (
        public.is_admin() or public.is_warehouse()
        or (public.current_role() = 'customer' and r.customer_id = public.current_customer_id())
        or (public.current_role() = 'sales_rep' and c.sales_rep_id = auth.uid())
      )
  );
$$;

create or replace function public.request_is_own_draft(p_request_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.customer_order_requests r
    join public.customers c on c.id = r.customer_id
    where r.id = p_request_id
      and r.status = 'draft'
      and (
        (public.current_role() = 'customer' and r.customer_id = public.current_customer_id())
        or (public.current_role() = 'sales_rep' and c.sales_rep_id = auth.uid())
      )
  );
$$;

create or replace function public.customer_order_requests_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    if public.current_role() = 'customer' then
      if old.status <> 'draft' or old.customer_id is distinct from public.current_customer_id() then
        raise exception 'Only a draft order can be deleted';
      end if;
    end if;
    return old;
  end if;

  if new.status = 'accepted' and not (public.is_admin() or public.is_warehouse()) then
    raise exception 'Staff accept an order request';
  end if;

  if public.current_role() = 'customer' then
    if new.customer_id is distinct from public.current_customer_id() then
      raise exception 'Not your account';
    end if;
    if tg_op = 'INSERT' then
      if new.status <> 'draft' then
        raise exception 'Start with a draft';
      end if;
      new.created_by := auth.uid();
    else
      if old.customer_id is distinct from public.current_customer_id() then
        raise exception 'Not your account';
      end if;
      if old.status <> 'draft' then
        raise exception 'This order can no longer be changed';
      end if;
      if new.status not in ('draft', 'submitted') then
        raise exception 'Send the order or keep it a draft';
      end if;
      if new.status = 'submitted' then
        new.submitted_at := now();
      end if;
    end if;
  end if;

  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end;
$$;

drop trigger if exists customer_order_requests_guard on public.customer_order_requests;
create trigger customer_order_requests_guard
  before insert or update or delete on public.customer_order_requests
  for each row
  execute function public.customer_order_requests_guard();

alter table public.customer_order_requests enable row level security;
alter table public.customer_order_request_products enable row level security;
alter table public.customer_order_request_cells enable row level security;

create policy cor_select on public.customer_order_requests
  for select to authenticated
  using (public.request_visible(id));

create policy cor_insert on public.customer_order_requests
  for insert to authenticated
  with check (
    (
      public.current_role() = 'customer'
      and customer_id = public.current_customer_id()
      and status = 'draft'
    )
    or (
      public.current_role() = 'sales_rep'
      and exists (
        select 1 from public.customers c
        where c.id = customer_id and c.sales_rep_id = auth.uid()
      )
    )
  );

create policy cor_update on public.customer_order_requests
  for update to authenticated
  using (public.request_is_own_draft(id))
  with check (public.request_visible(id));

create policy cor_delete on public.customer_order_requests
  for delete to authenticated
  using (public.request_is_own_draft(id));

create policy corp_select on public.customer_order_request_products
  for select to authenticated
  using (public.request_visible(request_id));

create policy corp_write on public.customer_order_request_products
  for all to authenticated
  using (public.request_is_own_draft(request_id))
  with check (public.request_is_own_draft(request_id));

create policy corc_select on public.customer_order_request_cells
  for select to authenticated
  using (public.request_visible(request_id));

create policy corc_write on public.customer_order_request_cells
  for all to authenticated
  using (public.request_is_own_draft(request_id))
  with check (public.request_is_own_draft(request_id));

grant select, insert, update, delete on public.customer_order_requests to authenticated;
grant select, insert, update, delete on public.customer_order_request_products to authenticated;
grant select, insert, update, delete on public.customer_order_request_cells to authenticated;
grant usage, select on sequence public.customer_order_requests_request_no_seq to authenticated;

revoke all on function public.current_customer_id() from public;
revoke all on function public.request_visible(uuid) from public;
revoke all on function public.request_is_own_draft(uuid) from public;
grant execute on function public.current_customer_id() to authenticated;
grant execute on function public.request_visible(uuid) to authenticated;
grant execute on function public.request_is_own_draft(uuid) to authenticated;

create policy read_customers_self on public.customers
  for select to authenticated
  using (public.current_role() = 'customer' and id = public.current_customer_id());

create policy read_c_addr_self on public.customer_addresses
  for select to authenticated
  using (public.current_role() = 'customer' and customer_id = public.current_customer_id());
