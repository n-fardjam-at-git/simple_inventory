-- Account serial for customers. Sage stays in account_number.

alter table public.customers
  add column account_no integer;

with numbered as (
  select id, row_number() over (order by company_name, id)::integer as n
  from public.customers
)
update public.customers as c
set account_no = numbered.n
from numbered
where c.id = numbered.id;

alter table public.customers
  alter column account_no set not null;

alter table public.customers
  alter column account_no add generated by default as identity;

select setval(
  pg_get_serial_sequence('public.customers', 'account_no'),
  greatest(coalesce((select max(account_no) from public.customers), 1), 1),
  (select exists (select 1 from public.customers))
);

alter table public.customers
  add constraint customers_account_no_key unique (account_no);

grant usage, select on sequence public.customers_account_no_seq to authenticated;
