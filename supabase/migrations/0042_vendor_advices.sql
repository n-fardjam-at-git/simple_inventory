-- Party on the login, plus vendor shipment advice (not the receiving chain).
-- Run in the Supabase SQL editor.

alter table public.profiles
  add column if not exists vendor_id uuid references public.vendors(id),
  add column if not exists customer_id uuid references public.customers(id);

create index if not exists profiles_vendor_idx on public.profiles (vendor_id);
create index if not exists profiles_customer_idx on public.profiles (customer_id);

alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles
  add constraint profiles_role_check
  check (role in ('admin', 'warehouse', 'sales_rep', 'customer', 'vendor'));

alter table public.profiles drop constraint if exists profiles_party_role;
alter table public.profiles
  add constraint profiles_party_role check (
    (role = 'vendor' and vendor_id is not null and customer_id is null)
    or (role = 'customer' and vendor_id is null)
    or (role in ('admin', 'warehouse', 'sales_rep') and vendor_id is null and customer_id is null)
  );

create or replace function public.current_vendor_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select vendor_id from public.profiles where id = auth.uid() and role = 'vendor';
$$;

create table public.vendor_advices (
  id uuid primary key default gen_random_uuid(),
  advice_num int generated by default as identity,
  vendor_id uuid not null references public.vendors(id),
  ship_date date,
  air_way_no text,
  notes text,
  status text not null default 'draft' check (status in ('draft', 'submitted', 'accepted')),
  submitted_at timestamptz,
  accepted_shipment_id uuid references public.vendor_shipments(id),
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  unique (advice_num)
);

create index vendor_advices_vendor_idx on public.vendor_advices (vendor_id);
create index vendor_advices_status_idx on public.vendor_advices (status);

create table public.vendor_advice_products (
  id uuid primary key default gen_random_uuid(),
  advice_id uuid not null references public.vendor_advices(id) on delete cascade,
  cutting_order_id uuid not null references public.cutting_orders(id),
  product_id uuid not null references public.products(id),
  unique (advice_id, cutting_order_id, product_id),
  foreign key (cutting_order_id, product_id)
    references public.cutting_order_products (cutting_order_id, product_id)
);

create index vendor_advice_products_advice_idx
  on public.vendor_advice_products (advice_id);

create table public.vendor_advice_cells (
  advice_product_id uuid not null references public.vendor_advice_products(id) on delete cascade,
  size_id uuid not null references public.size_chart_sizes(id),
  drop_id uuid not null references public.size_chart_drops(id),
  qty int not null default 0 check (qty >= 0),
  primary key (advice_product_id, size_id, drop_id)
);

create or replace function public.vendor_advices_guard()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    if public.current_role() <> 'vendor'
      or old.vendor_id is distinct from public.current_vendor_id() then
      raise exception 'not allowed';
    end if;
    if old.status <> 'draft' then
      raise exception 'advice is locked';
    end if;
    return old;
  end if;

  if tg_op = 'INSERT' then
    if public.current_role() <> 'vendor' or public.current_vendor_id() is null then
      raise exception 'not allowed';
    end if;
    new.vendor_id := public.current_vendor_id();
    new.status := 'draft';
    new.accepted_shipment_id := null;
    new.submitted_at := null;
    new.created_by := auth.uid();
    return new;
  end if;

  if public.current_role() = 'vendor' then
    if old.vendor_id is distinct from public.current_vendor_id() then
      raise exception 'not allowed';
    end if;
    if old.status <> 'draft' then
      raise exception 'advice is locked';
    end if;
    new.vendor_id := old.vendor_id;
    new.advice_num := old.advice_num;
    new.accepted_shipment_id := null;
    new.created_by := old.created_by;
    if new.status not in ('draft', 'submitted') then
      raise exception 'status not allowed';
    end if;
    if new.status = 'submitted' then
      new.submitted_at := now();
    else
      new.submitted_at := null;
    end if;
    return new;
  end if;

  if public.is_admin() or public.is_warehouse() then
    new.vendor_id := old.vendor_id;
    new.advice_num := old.advice_num;
    new.ship_date := old.ship_date;
    new.air_way_no := old.air_way_no;
    new.notes := old.notes;
    new.created_by := old.created_by;
    if old.status = 'submitted' and new.status = 'accepted' then
      if new.accepted_shipment_id is null then
        raise exception 'accepted shipment required';
      end if;
      return new;
    end if;
    if old.status = 'submitted' and new.status = 'draft' then
      new.accepted_shipment_id := null;
      new.submitted_at := null;
      return new;
    end if;
    raise exception 'status not allowed';
  end if;

  raise exception 'not allowed';
end;
$$;

create trigger vendor_advices_guard
  before insert or update or delete on public.vendor_advices
  for each row execute function public.vendor_advices_guard();

create or replace function public.vendor_advice_editable(p_advice_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.vendor_advices a
    where a.id = p_advice_id
      and a.status = 'draft'
      and a.vendor_id = public.current_vendor_id()
  );
$$;

create or replace function public.vendor_advice_cell_editable(p_line_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.vendor_advice_editable(
    (select advice_id from public.vendor_advice_products where id = p_line_id)
  );
$$;

create or replace function public.vendor_advice_lines_guard()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  aid uuid;
  vid uuid;
begin
  if tg_op = 'DELETE' then
    aid := old.advice_id;
  else
    aid := new.advice_id;
  end if;

  select a.vendor_id into vid from public.vendor_advices a where a.id = aid;

  if tg_table_name = 'vendor_advice_products' and tg_op = 'INSERT' then
    if not exists (
      select 1
      from public.cutting_orders co
      join public.cutting_order_products cop
        on cop.cutting_order_id = co.id
       and cop.product_id = new.product_id
      where co.id = new.cutting_order_id
        and co.vendor_id = vid
        and co.status is true
    ) then
      raise exception 'product is not on an open cutting for this factory';
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

create trigger vendor_advice_products_guard
  before insert or update or delete on public.vendor_advice_products
  for each row execute function public.vendor_advice_lines_guard();

create or replace function public.accept_vendor_advice(p_advice_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  adv public.vendor_advices;
  sid uuid;
  line public.vendor_advice_products;
  new_line uuid;
begin
  if not (public.is_admin() or public.is_warehouse()) then
    raise exception 'not allowed';
  end if;

  select * into adv from public.vendor_advices where id = p_advice_id for update;
  if not found then
    raise exception 'advice not found';
  end if;
  if adv.status <> 'submitted' then
    raise exception 'advice is not submitted';
  end if;

  insert into public.vendor_shipments (vendor_id, received_date, air_way_no)
  values (adv.vendor_id, current_date, adv.air_way_no)
  returning id into sid;

  for line in
    select * from public.vendor_advice_products where advice_id = adv.id
  loop
    insert into public.vendor_shipment_products (shipment_id, cutting_order_id, product_id)
    values (sid, line.cutting_order_id, line.product_id)
    returning id into new_line;

    insert into public.vendor_shipment_cells (shipment_product_id, size_id, drop_id, qty)
    select new_line, c.size_id, c.drop_id, c.qty
    from public.vendor_advice_cells c
    where c.advice_product_id = line.id
      and c.qty > 0;
  end loop;

  update public.vendor_advices
  set status = 'accepted', accepted_shipment_id = sid
  where id = adv.id;

  return sid;
end;
$$;

create or replace function public.return_vendor_advice(p_advice_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not (public.is_admin() or public.is_warehouse()) then
    raise exception 'not allowed';
  end if;

  update public.vendor_advices
  set status = 'draft'
  where id = p_advice_id
    and status = 'submitted';

  if not found then
    raise exception 'advice is not submitted';
  end if;
end;
$$;

