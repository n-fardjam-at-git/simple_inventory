alter table public.vendor_advice_cells enable row level security;

create policy vendor_advices_select on public.vendor_advices
  for select to authenticated
  using (
    public.is_admin()
    or public.is_warehouse()
    or vendor_id = public.current_vendor_id()
  );

create policy vendor_advices_insert on public.vendor_advices
  for insert to authenticated
  with check (
    public.current_role() = 'vendor'
    and vendor_id = public.current_vendor_id()
    and status = 'draft'
  );

create policy vendor_advices_update on public.vendor_advices
  for update to authenticated
  using (
    public.current_role() = 'vendor'
    and vendor_id = public.current_vendor_id()
    and status = 'draft'
  )
  with check (
    public.current_role() = 'vendor'
    and vendor_id = public.current_vendor_id()
    and status in ('draft', 'submitted')
  );

create policy vendor_advices_delete on public.vendor_advices
  for delete to authenticated
  using (
    public.current_role() = 'vendor'
    and vendor_id = public.current_vendor_id()
    and status = 'draft'
  );

create policy vendor_advice_products_select on public.vendor_advice_products
  for select to authenticated
  using (
    public.is_admin()
    or public.is_warehouse()
    or exists (
      select 1 from public.vendor_advices a
      where a.id = advice_id
        and a.vendor_id = public.current_vendor_id()
    )
  );

create policy vendor_advice_products_insert on public.vendor_advice_products
  for insert to authenticated
  with check (public.vendor_advice_editable(advice_id));

create policy vendor_advice_products_update on public.vendor_advice_products
  for update to authenticated
  using (public.vendor_advice_editable(advice_id))
  with check (public.vendor_advice_editable(advice_id));

create policy vendor_advice_products_delete on public.vendor_advice_products
  for delete to authenticated
  using (public.vendor_advice_editable(advice_id));

create policy vendor_advice_cells_select on public.vendor_advice_cells
  for select to authenticated
  using (
    public.is_admin()
    or public.is_warehouse()
    or exists (
      select 1
      from public.vendor_advice_products p
      join public.vendor_advices a on a.id = p.advice_id
      where p.id = advice_product_id
        and a.vendor_id = public.current_vendor_id()
    )
  );

create policy vendor_advice_cells_insert on public.vendor_advice_cells
  for insert to authenticated
  with check (public.vendor_advice_cell_editable(advice_product_id));

create policy vendor_advice_cells_update on public.vendor_advice_cells
  for update to authenticated
  using (public.vendor_advice_cell_editable(advice_product_id))
  with check (public.vendor_advice_cell_editable(advice_product_id));

create policy vendor_advice_cells_delete on public.vendor_advice_cells
  for delete to authenticated
  using (public.vendor_advice_cell_editable(advice_product_id));

create policy vendors_own on public.vendors
  for select to authenticated
  using (id = public.current_vendor_id());

create policy cutting_vendor_read on public.cutting_orders
  for select to authenticated
  using (vendor_id = public.current_vendor_id());

create policy cop_vendor_read on public.cutting_order_products
  for select to authenticated
  using (
    exists (
      select 1 from public.cutting_orders co
      where co.id = cutting_order_id
        and co.vendor_id = public.current_vendor_id()
    )
  );

create policy products_vendor_cutting on public.products
  for select to authenticated
  using (
    public.current_role() = 'vendor'
    and (
      exists (
        select 1
        from public.cutting_order_products cop
        join public.cutting_orders co on co.id = cop.cutting_order_id
        where cop.product_id = products.id
          and co.vendor_id = public.current_vendor_id()
      )
      or exists (
        select 1
        from public.vendor_advice_products vap
        join public.vendor_advices a on a.id = vap.advice_id
        where vap.product_id = products.id
          and a.vendor_id = public.current_vendor_id()
      )
    )
  );

