create table public.customer_orders (
  id uuid primary key default gen_random_uuid(),
  order_no integer generated by default as identity,
  customer_id uuid not null references public.customers(id),
  status text not null default 'pending' check (status in (
    'pending', 'approved', 'picking', 'back_order', 'short_shipped', 'complete', 'canceled'
  )),
  future_season text,
  start_date date,
  cancel_date date,
  shipping_method text,
  terms text,
  transmission_method text,
  ship_address_line1 text,
  ship_address_line2 text,
  ship_city text,
  ship_region text,
  ship_postal_code text,
  ship_country text,
  bill_address_line1 text,
  bill_address_line2 text,
  bill_city text,
  bill_region text,
  bill_postal_code text,
  bill_country text,
  sales_rep_id uuid references public.profiles(id),
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  notes text,
  unique (order_no)
);

create table public.customer_order_products (
  customer_order_id uuid not null references public.customer_orders(id) on delete cascade,
  product_id uuid not null references public.products(id),
  price numeric(12,2) not null default 0 check (price >= 0),
  commission_rate numeric(5,4) check (
    commission_rate is null or (commission_rate >= 0 and commission_rate <= 1)
  ),
  status text not null default 'pending' check (status in (
    'pending', 'back_order', 'short_shipped', 'complete', 'canceled'
  )),
  primary key (customer_order_id, product_id)
);

create table public.customer_order_cells (
  customer_order_id uuid not null,
  product_id uuid not null,
  size_id uuid not null references public.size_chart_sizes(id),
  drop_id uuid not null references public.size_chart_drops(id),
  qty int not null default 0 check (qty >= 0),
  qty_shipped int not null default 0 check (qty_shipped >= 0),
  price numeric(12,2) check (price is null or price >= 0),
  primary key (customer_order_id, product_id, size_id, drop_id),
  foreign key (customer_order_id, product_id)
    references public.customer_order_products (customer_order_id, product_id)
    on delete cascade
);

create or replace function public.customer_order_rollup_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  oid uuid;
  n int;
  n_cancel int;
  n_complete int;
  n_short int;
  n_back int;
  n_pending int;
  n_active int;
  current_status text;
  next_status text;
begin
  oid := coalesce(new.customer_order_id, old.customer_order_id);

  select
    count(*),
    count(*) filter (where status = 'canceled'),
    count(*) filter (where status = 'complete'),
    count(*) filter (where status = 'short_shipped'),
    count(*) filter (where status = 'back_order'),
    count(*) filter (where status = 'pending')
  into n, n_cancel, n_complete, n_short, n_back, n_pending
  from public.customer_order_products
  where customer_order_id = oid;

  if coalesce(n, 0) = 0 then
    return null;
  end if;

  n_active := n_pending + n_back;
  select status into current_status from public.customer_orders where id = oid;

  if n_cancel = n then
    next_status := 'canceled';
  elsif n_complete + n_cancel = n and n_complete > 0 then
    next_status := 'complete';
  elsif n_active = 0 and n_short > 0 then
    next_status := 'short_shipped';
  elsif n_back > 0 then
    next_status := 'back_order';
  elsif n_pending > 0 and (n_short > 0 or n_complete > 0) then
    next_status := 'back_order';
  elsif n_pending + n_cancel = n and n_pending > 0 then
    if current_status in ('pending', 'approved', 'picking') then
      next_status := current_status;
    else
      next_status := 'pending';
    end if;
  else
    next_status := current_status;
  end if;

  if next_status is distinct from current_status then
    update public.customer_orders
    set status = next_status, updated_at = now()
    where id = oid;
  end if;
  return null;
end;
$$;

create trigger customer_order_products_rollup
after insert or update of status or delete on public.customer_order_products
for each row execute function public.customer_order_rollup_status();

