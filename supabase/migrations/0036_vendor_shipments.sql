-- Vendor receiving: one shipment can cover several cuttings; same product
-- may appear once per cutting on that shipment.

create table public.vendor_shipments (
  id uuid primary key default gen_random_uuid(),
  shipment_num int generated by default as identity,
  received_date date not null default (current_date),
  air_way_no text,
  posted boolean not null default false,
  posted_at timestamptz,
  received_by uuid references public.profiles(id)
);

alter table public.vendor_shipments
  add constraint vendor_shipments_shipment_num_key unique (shipment_num);

create index vendor_shipments_received_date_idx
  on public.vendor_shipments (received_date desc);

create table public.vendor_shipment_products (
  id uuid primary key default gen_random_uuid(),
  shipment_id uuid not null references public.vendor_shipments(id) on delete cascade,
  cutting_order_id uuid not null references public.cutting_orders(id),
  product_id uuid not null references public.products(id),
  unique (shipment_id, cutting_order_id, product_id),
  foreign key (cutting_order_id, product_id)
    references public.cutting_order_products (cutting_order_id, product_id)
);

create index vendor_shipment_products_shipment_idx
  on public.vendor_shipment_products (shipment_id);

create index vendor_shipment_products_cutting_idx
  on public.vendor_shipment_products (cutting_order_id);

create table public.vendor_shipment_cells (
  shipment_product_id uuid not null references public.vendor_shipment_products(id) on delete cascade,
  size_id uuid not null references public.size_chart_sizes(id),
  drop_id uuid not null references public.size_chart_drops(id),
  qty int not null default 0 check (qty >= 0),
  primary key (shipment_product_id, size_id, drop_id)
);

create index vendor_shipment_cells_line_idx
  on public.vendor_shipment_cells (shipment_product_id);

alter table public.stock_movements
  add column if not exists vendor_shipment_id uuid references public.vendor_shipments(id);

create or replace function public.vendor_shipment_is_posted(p_shipment_id uuid)
returns boolean
language sql
stable
set search_path = public
as $$
  select coalesce((select posted from public.vendor_shipments where id = p_shipment_id), false);
$$;

create or replace function public.vendor_shipments_guard()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  sid uuid;
begin
  if tg_table_name = 'vendor_shipments' then
    if tg_op = 'DELETE' then
      if old.posted then
        raise exception 'shipment is posted';
      end if;
      return old;
    end if;
    if tg_op = 'UPDATE' and old.posted then
      raise exception 'shipment is posted';
    end if;
    return new;
  end if;

  if tg_op = 'DELETE' then
    if tg_table_name = 'vendor_shipment_products' then
      sid := old.shipment_id;
    else
      select shipment_id into sid
      from public.vendor_shipment_products
      where id = old.shipment_product_id;
    end if;
    if public.vendor_shipment_is_posted(sid) then
      raise exception 'shipment is posted';
    end if;
    return old;
  end if;

  if tg_table_name = 'vendor_shipment_products' then
    sid := new.shipment_id;
  else
    select shipment_id into sid
    from public.vendor_shipment_products
    where id = new.shipment_product_id;
  end if;
  if public.vendor_shipment_is_posted(sid) then
    raise exception 'shipment is posted';
  end if;
  return new;
end;
$$;

drop trigger if exists vendor_shipments_guard on public.vendor_shipments;
create trigger vendor_shipments_guard
  before update or delete on public.vendor_shipments
  for each row execute function public.vendor_shipments_guard();

drop trigger if exists vendor_shipment_products_guard on public.vendor_shipment_products;
create trigger vendor_shipment_products_guard
  before insert or update or delete on public.vendor_shipment_products
  for each row execute function public.vendor_shipments_guard();

drop trigger if exists vendor_shipment_cells_guard on public.vendor_shipment_cells;
create trigger vendor_shipment_cells_guard
  before insert or update or delete on public.vendor_shipment_cells
  for each row execute function public.vendor_shipments_guard();

create or replace function public.post_vendor_shipment(p_shipment_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  rec record;
begin
  if not (public.is_admin() or public.is_warehouse()) then
    raise exception 'not allowed';
  end if;
  if not exists (select 1 from public.vendor_shipments where id = p_shipment_id) then
    raise exception 'shipment not found';
  end if;
  if public.vendor_shipment_is_posted(p_shipment_id) then
    raise exception 'already posted';
  end if;

  for rec in
    select
      sp.cutting_order_id,
      sp.product_id,
      c.size_id,
      c.drop_id,
      c.qty
    from public.vendor_shipment_products sp
    join public.vendor_shipment_cells c on c.shipment_product_id = sp.id
    where sp.shipment_id = p_shipment_id
      and c.qty <> 0
  loop
    insert into public.inventory (product_id, size_id, drop_id, qty_on_hand, reorder_point)
    values (rec.product_id, rec.size_id, rec.drop_id, rec.qty, 0)
    on conflict (product_id, size_id, drop_id)
    do update set qty_on_hand = public.inventory.qty_on_hand + excluded.qty_on_hand;

    insert into public.cutting_quantities (
      cutting_order_id, product_id, size_id, drop_id, qty_ordered, qty_received
    )
    values (
      rec.cutting_order_id, rec.product_id, rec.size_id, rec.drop_id, 0, rec.qty
    )
    on conflict (cutting_order_id, product_id, size_id, drop_id)
    do update set qty_received = public.cutting_quantities.qty_received + excluded.qty_received;

    insert into public.stock_movements (
      type, qty, product_id, size_id, drop_id, vendor_shipment_id, user_id
    ) values (
      'receive', rec.qty, rec.product_id, rec.size_id, rec.drop_id, p_shipment_id, auth.uid()
    );
  end loop;

  update public.vendor_shipments
  set posted = true, posted_at = now(), received_by = auth.uid()
  where id = p_shipment_id;
end;
$$;

create or replace function public.retarget_drop(p_from uuid, p_to uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_from is null or p_to is null or p_from = p_to then
    return;
  end if;

  insert into public.product_drops (product_id, drop_id)
  select product_id, p_to from public.product_drops where drop_id = p_from
  on conflict do nothing;
  delete from public.product_drops where drop_id = p_from;

  insert into public.inventory (product_id, size_id, drop_id, qty_on_hand, reorder_point)
  select product_id, size_id, p_to, qty_on_hand, reorder_point
  from public.inventory
  where drop_id = p_from
  on conflict (product_id, size_id, drop_id) do update
  set
    qty_on_hand = public.inventory.qty_on_hand + excluded.qty_on_hand,
    reorder_point = greatest(public.inventory.reorder_point, excluded.reorder_point);
  delete from public.inventory where drop_id = p_from;

  insert into public.product_price_upcharges (product_id, size_id, drop_id, upcharge_amount)
  select product_id, size_id, p_to, upcharge_amount
  from public.product_price_upcharges
  where drop_id = p_from
  on conflict (product_id, size_id, drop_id) do update
  set upcharge_amount = greatest(
    public.product_price_upcharges.upcharge_amount,
    excluded.upcharge_amount
  );
  delete from public.product_price_upcharges where drop_id = p_from;

  insert into public.customer_shipment_cells (
    customer_shipment_product_id, size_id, drop_id, qty
  )
  select customer_shipment_product_id, size_id, p_to, qty
  from public.customer_shipment_cells
  where drop_id = p_from
  on conflict (customer_shipment_product_id, size_id, drop_id) do update
  set qty = public.customer_shipment_cells.qty + excluded.qty;
  delete from public.customer_shipment_cells where drop_id = p_from;

  insert into public.cutting_shipment_cells (
    cutting_shipment_product_id, size_id, drop_id, qty
  )
  select cutting_shipment_product_id, size_id, p_to, qty
  from public.cutting_shipment_cells
  where drop_id = p_from
  on conflict (cutting_shipment_product_id, size_id, drop_id) do update
  set qty = public.cutting_shipment_cells.qty + excluded.qty;
  delete from public.cutting_shipment_cells where drop_id = p_from;

  insert into public.vendor_shipment_cells (
    shipment_product_id, size_id, drop_id, qty
  )
  select shipment_product_id, size_id, p_to, qty
  from public.vendor_shipment_cells
  where drop_id = p_from
  on conflict (shipment_product_id, size_id, drop_id) do update
  set qty = public.vendor_shipment_cells.qty + excluded.qty;
  delete from public.vendor_shipment_cells where drop_id = p_from;

  update public.stock_movements set drop_id = p_to where drop_id = p_from;
end;
$$;

